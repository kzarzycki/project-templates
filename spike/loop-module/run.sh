#!/usr/bin/env bash
# Spike for #164: copier loop module. Generates a project with the loop off, turns it on, turns it off,
# turns it on again (diff at each step), then checks independent updates and the "existing loop-on project" migration.
# Throwaway; templates here are small stand-ins that use the same kinds of shared file as the real ones
# (ci.yml, mise.toml, PR template, agent instructions). Needs copier 9.17.0 (the repo's pin) and git.
set -euo pipefail; . "$(dirname "$0")/lib.sh"
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
LOOP_ANS=.copier-answers.loop.yml
d() { git -C "$P" add -A; git -C "$P" -c core.pager=cat diff --cached --stat --format= ; git -C "$P" diff --cached -U0 | grep -E '^[+-][^+-]' | head -${1:-40} || true; git -C "$P" commit -qm "$2"; }

publish "$HERE/base-v2" "$W/base" v1.0.0
publish "$HERE/loop" "$W/loop" v1.0.0
P=$W/proj; mkdir $P; git -C $P init -q

step "1. base template, loop off"
(cd $P && cp_ copy -d project_name=demo "$W/base" .); d 5 base; ls -A $P | tr '\n' ' '; echo

step "2. loop ON later: copier copy --answers-file $LOOP_ANS (module added exactly these files)"
(cd $P && cp_ copy --answers-file $LOOP_ANS "$W/loop" .); d 40 loop-on
cat $P/$LOOP_ANS

step "3. loop OFF: copier update -a $LOOP_ANS -d loop_enabled=false"
(cd $P && cp_ update -a $LOOP_ANS -d loop_enabled=false); d 40 loop-off
echo "files left from the module: $(ls $P/docs/agents $P/.mise 2>&1 | tr '\n' ' ')"; cat $P/$LOOP_ANS

step "4. loop ON again: copier update -a $LOOP_ANS -d loop_enabled=true"
(cd $P && cp_ update -a $LOOP_ANS -d loop_enabled=true); d 40 loop-on-again

step "5. each template updates on its own"
echo "# changelog" >> "$W/base/README.md.jinja"; commit_all "$W/base" "base change"; git -C "$W/base" tag v1.1.0
(cd $P && cp_ update); d 10 "base update"
echo "(above: only the base's change; loop answers file untouched)"
echo "Gate: full" >> "$W/loop/files/docs/agents/{% if loop_enabled %}loop.md{% endif %}.jinja"; commit_all "$W/loop" "loop change"; git -C "$W/loop" tag v1.1.0
(cd $P && cp_ update -a $LOOP_ANS); d 10 "loop update"
echo "(above: only the loop's change; base answers file untouched)"
grep -H _commit $P/.copier-answers.yml $P/$LOOP_ANS

step "6. existing loop-on project (generated by base v1 with the loop inline), then base moves to v2"
publish "$HERE/base-v1" "$W/base6" v1.0.0
Q=$W/old; mkdir $Q; git -C $Q init -q
(cd $Q && cp_ copy -d project_name=demo -d engineering_loop=true "$W/base6" .); git -C $Q add -A; git -C $Q commit -qm gen-v1
cp -r $Q $W/old-original
retag "$W/base6" "$HERE/base-v2" v2.0.0
(cd $Q && cp_ update); P=$Q; echo "-- after base update to v2 alone (loop text removed from the base's render):"; d 40 base-v2
(cd $Q && cp_ copy --answers-file $LOOP_ANS -d components="src,tests" "$W/loop" .) ; P=$Q; echo "-- after applying the module once:"; d 40 module
echo "-- net difference from the original v1 project, all files:"
git -C $Q diff $(git -C $Q rev-list --max-parents=0 HEAD) HEAD --stat --format= || true
git -C $Q diff $(git -C $Q rev-list --max-parents=0 HEAD) HEAD -U0 | grep -E '^[+-][^+-]' || true
echo "DONE rc=0"
